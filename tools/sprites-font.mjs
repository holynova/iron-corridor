/** Glyphs laid out in a horizontal strip; the engine slices by frame index. */
export function fontStrip() {
  const keys = Object.keys(G);
  const g = new Grid(keys.length * 8, 8);
  keys.forEach((k, i) => {
    const rows = G[k];
    for (let y = 0; y < 8; y++) {
      const bits = rows[y];
      for (let x = 0; x < 8; x++) if (bits & (0x10 >> x)) g.set(i * 8 + x, y, 'W');
    }
  });
  g.charOrder = keys;
  return g;
}

export const FONT_ORDER = Object.keys(G);
export function fontIndex(ch) {
  const i = FONT_ORDER.indexOf(ch);
  return i < 0 ? FONT_ORDER.indexOf(' ') : i;
}

/** Emits a TypeScript copy of the glyph order so the renderer can import it. */
export function writeFontMap(outPath) {
  const json = JSON.stringify(FONT_ORDER);
  const body = `// GENERATED by tools/sprites-font.mjs — do not edit by hand.\n` +
    `// Index of each glyph in the baked 'pxfont' strip.\nexport const FONT_ORDER = ${json} as const;\n\n` +
    `export function fontIndex(ch: string): number {\n` +
    `  const i = (FONT_ORDER as readonly string[]).indexOf(ch);\n` +
    `  return i < 0 ? (FONT_ORDER as readonly string[]).indexOf(' ') : i;\n}\n`;
  writeFileSync(outPath, body);
}
